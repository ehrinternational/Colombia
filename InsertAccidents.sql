-- ==========================================================================================
-- INSERT ACCIDENT RECORD (SOAT / ARL REGULATORY CAPTURE)
-- TARGET ARCHITECTURE: SQL Server 2014+ / Azure SQL Database
-- ==========================================================================================

IF OBJECT_ID('dbo.COLInsertAccidents', 'P') IS NOT NULL
    DROP PROCEDURE dbo.COLInsertAccidents;
GO

CREATE PROCEDURE dbo.COLInsertAccidents
    @AccidentGuid NVARCHAR(50) = NULL,
    @PatientVisit NVARCHAR(50),
    @AccidentType INT = NULL,
    @Description NVARCHAR(500) = NULL,
    @Arl BIT = NULL,
    @ArlNumber VARCHAR(20) = NULL,
    @FuratNumber VARCHAR(20) = NULL,
    @DateTime DATETIME = NULL,
    @Zone VARCHAR(2) = NULL,
    @AccLocation NVARCHAR(255) = NULL,
    @StateCode VARCHAR(10) = NULL,
    @State NVARCHAR(100) = NULL,
    @MunicipalCode VARCHAR(10) = NULL,
    @Municipality NVARCHAR(100) = NULL,
    @SubType VARCHAR(2) = NULL,
    @Condition VARCHAR(2) = NULL,
    @Insurance VARCHAR(2) = NULL,
    @VehicleType VARCHAR(2) = NULL,
    @LicensePlate VARCHAR(10) = NULL,
    @InsuranceCode VARCHAR(6) = NULL,
    @Policy VARCHAR(20) = NULL,
    @Limit BIT = NULL,
    @PolicyStart DATE = NULL,
    @PolicyEnd DATE = NULL,
    @RegistroSIRAS NVARCHAR(60) = NULL,
    @DocumentType VARCHAR(5) = NULL,
    @DocumentNumber VARCHAR(20) = NULL,
    @OwnerName NVARCHAR(30) = NULL,
    @OwnerSecondName NVARCHAR(30) = NULL,
    @OwnerMiddleName NVARCHAR(30) = NULL,
    @OwnerLastName NVARCHAR(30) = NULL,
    @OwnerAddress NVARCHAR(100) = NULL,
    @OwnerPhone VARCHAR(20) = NULL,
    @OwnerStateCode VARCHAR(10) = NULL,
    @OwnerState NVARCHAR(100) = NULL,
    @OwnerMunicipalityCode VARCHAR(10) = NULL,
    @OwnerMunicipality NVARCHAR(100) = NULL,
    @DriverDocumentType VARCHAR(5) = NULL,
    @DriverDocumentNumber VARCHAR(20) = NULL,
    @DriverName NVARCHAR(30) = NULL,
    @DriverSecondName NVARCHAR(30) = NULL,
    @DriverMiddleName NVARCHAR(30) = NULL,
    @DriverLastName NVARCHAR(30) = NULL,
    @DriverAddress NVARCHAR(100) = NULL,
    @DriverTelephone VARCHAR(20) = NULL,
    @DriverStateCode VARCHAR(10) = NULL,
    @DriverState NVARCHAR(100) = NULL,
    @DriverMunicipalCode VARCHAR(10) = NULL,
    @DriverMunicipality NVARCHAR(100) = NULL,
    @CreatedBy NVARCHAR(100) = NULL
AS
BEGIN
    SET NOCOUNT ON;

    INSERT INTO dbo.Accident (
        AccidentGuid,
        PatientVisit,
        AccidentType,
        Description,
        Arl,
        ArlNumber,
        FuratNumber,
        DateTime,
        Zone,
        AccLocation,
        StateCode,
        State,
        MunicipalCode,
        Municipality,
        SubType,
        Condition,
        Insurance,
        VehicleType,
        LicensePlate,
        InsuranceCode,
        Policy,
        Limit,
        PolicyStart,
        PolicyEnd,
        RegistroSIRAS,
        DocumentType,
        DocumentNumber,
        OwnerName,
        OwnerSecondName,
        OwnerMiddleName,
        OwnerLastName,
        OwnerAddress,
        OwnerPhone,
        OwnerStateCode,
        OwnerState,
        OwnerMunicipalityCode,
        OwnerMunicipality,
        DriverDocumentType,
        DriverDocumentNumber,
        DriverName,
        DriverSecondName,
        DriverMiddleName,
        DriverLastName,
        DriverAddress,
        DriverTelephone,
        DriverStateCode,
        DriverState,
        DriverMunicipalCode,
        DriverMunicipality,
        CreatedDate,
        CreatedBy
    )
    VALUES (
        COALESCE(NULLIF(@AccidentGuid, N''), CONVERT(NVARCHAR(50), NEWID())),
        @PatientVisit,
        @AccidentType,
        @Description,
        @Arl,
        CASE WHEN @Arl = 1 THEN @ArlNumber ELSE NULL END,
        CASE WHEN @Arl = 1 THEN @FuratNumber ELSE NULL END,
        @DateTime,
        @Zone,
        @AccLocation,
        @StateCode,
        @State,
        @MunicipalCode,
        @Municipality,
        @SubType,
        @Condition,
        @Insurance,
        @VehicleType,
        @LicensePlate,
        @InsuranceCode,
        @Policy,
        @Limit,
        @PolicyStart,
        @PolicyEnd,
        @RegistroSIRAS,
        @DocumentType,
        @DocumentNumber,
        @OwnerName,
        @OwnerSecondName,
        @OwnerMiddleName,
        @OwnerLastName,
        @OwnerAddress,
        @OwnerPhone,
        @OwnerStateCode,
        @OwnerState,
        @OwnerMunicipalityCode,
        @OwnerMunicipality,
        @DriverDocumentType,
        @DriverDocumentNumber,
        @DriverName,
        @DriverSecondName,
        @DriverMiddleName,
        @DriverLastName,
        @DriverAddress,
        @DriverTelephone,
        @DriverStateCode,
        @DriverState,
        @DriverMunicipalCode,
        @DriverMunicipality,
        GETDATE(),
        @CreatedBy
    );
END;
GO
